from plugins.media_organizer.core.database import MediaDatabase


# =============================================================================
# REBUILD FUNCTIONS
# =============================================================================

def rebuild_db(db: MediaDatabase) -> str:
    """Консолидация дублирующихся записей в БД без обращения к модели.

    Объединяет записи с одинаковым path в рамках одного диска/типа:
    побеждает наиболее полная запись, остальные удаляются.

    Args:
        db (MediaDatabase): Экземпляр базы данных.

    Returns:
        str: Строка с итогами операции.

    Examples:
        >>> result = rebuild_db(MediaDatabase(MEDIA_DB))
    """
    removed = db.consolidate_duplicates()
    return f"✅ Консолидация завершена: удалено дублей — {removed}" if removed else "✅ Дублей не обнаружено"

